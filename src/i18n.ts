const dictionaries: Record<Lang, Record<Key, string>> = { en, ru, he, es, pt, ar, hi, id };
const RTL: Lang[] = ['he', 'ar'];

export const detectLang = (): Lang => {
  const prefs = typeof navigator !== 'undefined' ? [...(navigator.languages ?? []), navigator.language] : [];
  for (const tag of prefs) {
    const base = (tag || '').toLowerCase().split('-')[0];
    // legacy ISO codes some Android versions still report
    const norm = base === 'iw' ? 'he' : base === 'in' ? 'id' : base;
    if (norm in dictionaries) return norm as Lang;
  }
  return 'en';
};

export const lang: Lang = detectLang();
export const dir: 'ltr' | 'rtl' = RTL.includes(lang) ? 'rtl' : 'ltr';

export const t = (key: Key, vars: Record<string, string | number> = {}): string =>
  dictionaries[lang][key].replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
